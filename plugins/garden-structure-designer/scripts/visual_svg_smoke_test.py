# External Comment: Map a filename to sheet classification type (blueprint or drawing)
def sheet_kind(svg_path: str) -> str:
    """
    Identifies the categorization of the target sheet based on filename cues.
    
    Args:
        svg_path: Filename or path to the SVG.
        
    Returns:
        String "blueprint" if filename starts with blueprint-, otherwise "drawing".
    """
    name = os.path.basename(svg_path).lower()
    return "blueprint" if "blueprint-" in name else "drawing"

# External Comment: Generate a normalized sheet key identifier for looking up thresholds
def hub_sheet_key(svg_path: str) -> str:
    """
    Normalizes filename to match expected metric threshold keys.
    
    Args:
        svg_path: Filename or path to the SVG.
        
    Returns:
        Normalized key name string.
    """
    base = os.path.basename(svg_path).replace(".svg", "").lower()
    if "blueprint-isometric" in base:
        return "blueprint-isometric"
    if "drawing-isometric-view" in base:
        return "drawing-isometric"
    if "drawing-perspective-view" in base:
        return "drawing-perspective"
    return base

# External Comment: Translate 3D model coordinates into 2D isometric projected pixels
def project_iso(x_ft: float, y_ft: float, z_ft: float, scale: float, cx: float, cy: float) -> tuple[float, float]:
    """
    Performs parametric isometric projection calculations from 3D space to 2D pixels.
    
    Args:
        x_ft: X dimension in feet.
        y_ft: Y dimension in feet.
        z_ft: Z dimension in feet.
        scale: Scaling multiplier (pixels per foot).
        cx: Viewport horizontal center pivot.
        cy: Viewport vertical ground pivot.
        
    Returns:
        Tuple of (px_x, px_y) coordinates.
    """
    px = x_ft * scale
    py = y_ft * scale
    pz = z_ft * scale
    iso_x = cx + (px - py) * math.cos(math.radians(30))
    iso_y = cy + (px + py) * math.sin(math.radians(30)) - pz
    return iso_x, iso_y

# External Comment: Calculate central viewport crop bounding box for hub inspection
def compute_hub_crop(structure: dict[str, typing.Any], sheet_name: str) -> typing.Optional[tuple[int, int, int, int]]:
    """
    Computes a tight bounding box around the central structural hub assembly.
    
    Args:
        structure: Loaded structural design model.
        sheet_name: Target sheet filename.
        
    Returns:
        Optional tuple of (x, y, width, height) pixels, or None on error.
    """
    try:
        geom = structure["geometry"]
        coords = geom["svg_coordinates"]
        joints = geom["joints"]
        
        scale = coords.get("scale_px_per_ft") or 55.0
        cx = coords["width_px"] / 2
        
        post_h = geom["total_height"]["post_ft"]
        roof_r = geom["roof_rise"]["rise_ft"]
        
        if "perspective" in sheet_name or "isometric" in sheet_name:
            inscribed_r = structure["layout"]["inscribed_radius_ft"]
            sides = structure["layout"]["post_count"]
            span_diag = round(2 * inscribed_r / math.cos(math.pi / sides), 3)
            approx_h = post_h + roof_r + span_diag * 0.5
            available_h = coords["height_px"] - 250
            scale = min(scale, available_h / approx_h)
            cy = coords["height_px"] - 200
        else:
            cy = coords["height_px"] / 2 - 20
            
        Z_APEX = joints.get("z_planes", {}).get("Z_APEX", geom["total_height"]["total_height_ft"])
        hub_apex = [0.0, 0.0, Z_APEX]
        
        if "perspective" in sheet_name or "isometric" in sheet_name:
            p_hub = project_iso(hub_apex[0], hub_apex[1], hub_apex[2], scale, cx, cy)
        else:
            p_hub = (cx, cy)
            
        term_pts = joints.get("rafters", {}).get("hub_termination_points", {}).get("points", [])
        if not term_pts:
            return None
            
        max_r = 0.0
        for pt_item in term_pts:
            pt = pt_item["point"] if isinstance(pt_item, dict) and "point" in pt_item else pt_item
            if "perspective" in sheet_name or "isometric" in sheet_name:
                p_tip = project_iso(pt[0], pt[1], pt[2], scale, cx, cy)
            else:
                p_tip = (cx + pt[0] * 80.0, cy + pt[1] * 80.0)
            dist = math.sqrt((p_hub[0]-p_tip[0])**2 + (p_hub[1]-p_tip[1])**2)
            max_r = max(max_r, dist)
            
        crop_half = max(HUB_CROP_MIN_HALF, min(int(max_r * HUB_CROP_RADIUS_FACTOR), HUB_CROP_MAX_HALF))
        
        x_crop = int(p_hub[0] - crop_half)
        y_crop = int(p_hub[1] - crop_half)
        w_crop = int(crop_half * 2)
        h_crop = int(crop_half * 2)
        
        return (x_crop, y_crop, w_crop, h_crop)
    except Exception as e:
        print(f"Failed to compute hub crop: {e}")
        return None

# External Comment: Process raster screenshot and calculate basic layout metrics
def evaluate_image(img_path: str, kind: str) -> tuple[dict[str, typing.Any], list[str]]:
    """
    Validates simple visual heuristics like empty canvas, centering, or scale collapses.
    
    Args:
        img_path: File path of the PNG screenshot.
        kind: Classification "blueprint" or "drawing".
        
    Returns:
        Tuple of (metrics, failures).
    """
    metrics: dict[str, typing.Any] = {}
    failures: list[str] = []
    
    try:
        img = Image.open(img_path).convert("RGB")
        w, h = img.size
        metrics["viewport_px"] = [w, h]
        
        arr = np.array(img)
        corners = [arr[0,0], arr[0,-1], arr[-1,0], arr[-1,-1]]
        bg_color = np.median(corners, axis=0)
        
        diff = np.abs(arr - bg_color).sum(axis=2)
        non_bg_mask = diff > BG_EPS
        non_bg_ratio = np.sum(non_bg_mask) / (w * h)
        metrics["non_bg_ratio"] = float(non_bg_ratio)
        
        if non_bg_ratio < MIN_NON_BG_RATIO[kind]:
            failures.append("VISUAL_BLANK")
            
        if np.any(non_bg_mask):
            rows = np.any(non_bg_mask, axis=1)
            cols = np.any(non_bg_mask, axis=0)
            ymin, ymax = np.where(rows)[0][[0, -1]]
            xmin, xmax = np.where(cols)[0][[0, -1]]
            
            bbox_area = (ymax - ymin) * (xmax - xmin)
            bbox_fill_ratio = bbox_area / (w * h)
            metrics["bbox_fill_ratio"] = float(bbox_fill_ratio)
            
            if bbox_fill_ratio < MIN_BBOX_FILL_RATIO[kind]:
                failures.append("VISUAL_TINY_CLUSTER")
                
            if xmax < w * TOP_LEFT_CLUSTER_MAX_X and ymax < h * TOP_LEFT_CLUSTER_MAX_Y:
                metrics["top_left_clustered"] = True
                failures.append("VISUAL_TOP_LEFT_CLUSTER")
            else:
                metrics["top_left_clustered"] = False
        else:
            metrics["bbox_fill_ratio"] = 0.0
            metrics["top_left_clustered"] = False
            
    except Exception as e:
        failures.append(f"IMAGE_PROCESSING_ERROR: {e}")
        
    return metrics, failures

# External Comment: Process high-resolution hub crop and calculate edge density
def evaluate_hub_crop(img_path: str, sheet_key: str) -> tuple[dict[str, typing.Any], list[str]]:
    """
    Validates edge complexity inside the hub region to detect missing or corrupted joints.
    
    Args:
        img_path: File path of the cropped hub PNG.
        sheet_key: Normalized sheet key.
        
    Returns:
        Tuple of (metrics, failures).
    """
    metrics: dict[str, typing.Any] = {}
    failures: list[str] = []
    
    try:
        img = Image.open(img_path).convert("L")
        arr = np.array(img)
        
        dx = np.diff(arr, axis=1, append=arr[:, -1:])
        dy = np.diff(arr, axis=0, append=arr[-1:, :])
        mag = np.sqrt(dx**2 + dy**2)
        
        edge_mask = mag > 10
        edge_density = np.sum(edge_mask) / (arr.shape[0] * arr.shape[1])
        metrics["hub_edge_density"] = float(edge_density)
        
        max_thresh = HUB_EDGE_DENSITY_MAX.get(sheet_key) or 0.4
        min_thresh = 0.005
        
        if edge_density > max_thresh:
            failures.append("SPAGHETTI_HUB_RISK")
        elif edge_density < min_thresh:
            failures.append("HUB_CROP_EMPTY_OR_WRONG")
            
    except Exception as e:
        failures.append(f"HUB_PROCESSING_ERROR: {e}")
        
    return metrics, failures

# External Comment: Extracts expected framing member counts from structure spec model
def extract_expected_topology(structure: dict[str, typing.Any]) -> dict[str, int]:
    """
    Determines structural components quantities from specification.
    
    Args:
        structure: Design parameters model.
        
    Returns:
        Dict mapping element names (posts, beams, rafters) to integer counts.
    """
    layout = structure.get("layout", {})
    roof = structure.get("roof", {})
    hub = structure.get("hub", {})
    bracing = structure.get("bracing", {})
    
    brace_spec = bracing.get("brace", {})
    count_per_post = brace_spec.get("count_per_post")
    if count_per_post is None:
        count_per_post = 2 if bracing.get("layout") == "paired_per_post" else 1

    post_cnt = layout.get("post_count") or 0
    primary_cnt = (roof.get("primary_rafters") or {}).get("count") or 0
    return {
        "posts": post_cnt,
        "beams": post_cnt,
        "rafters": primary_cnt,
        "hub": 1 if hub.get("type") and hub.get("type") != "none" else 0,
        "braces": (post_cnt * count_per_post) if bracing.get("enabled") else 0
    }

# External Comment: Use Canny edges and Hough lines to detect posts, beams, rafters
def detect_components(image: np.ndarray) -> dict[str, int]:
    """
    Applies Canny filtering and probabilistic Hough line transforms to identify elements.
    
    Args:
        image: Multi-channel input image in BGR format.
        
    Returns:
        Dictionary mapping structural component types to estimated counts.
    """
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    edges = cv2.Canny(gray, 50, 150)

    lines = cv2.HoughLinesP(edges, 1, np.pi/180, 50, minLineLength=50, maxLineGap=10)

    posts = beams = rafters = 0

    if lines is None:
        return {"posts": 0, "beams": 0, "rafters": 0}

    for line in lines:
        x1, y1, x2, y2 = line[0]
        dx, dy = x2 - x1, y2 - y1
        angle = abs(np.degrees(np.arctan2(dy, dx)))
        length = (dx * dx + dy * dy) ** 0.5

        if 80 < angle < 100 and length > 80:
            posts += 1
        elif angle < 10 or angle > 170:
            beams += 1
        else:
            rafters += 1

    return {
        "posts": posts // 2,
        "beams": beams // 2,
        "rafters": rafters // 2
    }

# External Comment: Measure total non-empty drawing ink density on a gray canvas
def compute_content_ratio(image: np.ndarray) -> float:
    """
    Estimates the visual coverage of structural drawings to prevent complete collapses.
    
    Args:
        image: Multi-channel input image.
        
    Returns:
        Float coverage percentage.
    """
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    return float(np.count_nonzero(gray) / (gray.shape[0] * gray.shape[1]))

# External Comment: Measures detailed edge density within a central hub cropping box
def detect_hub_density(image: np.ndarray) -> int:
    """
    Calculates count of non-zero edge pixels in a central hub window to audit complexity.
    
    Args:
        image: Standard BGR input image.
        
    Returns:
        Integer representing count of active edge pixels.
    """
    h, w = image.shape[:2]
    cx, cy = w // 2, h // 2
    crop = image[max(0, cy - 100):min(h, cy + 100), max(0, cx - 100):min(w, cx + 100)]
    gray = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
    edges = cv2.Canny(gray, 50, 150)
    return int(np.count_nonzero(edges))

# External Comment: Compares computer vision detections with expectations
def full_visual_validation(
    image: np.ndarray,
    structure: dict[str, typing.Any],
    sheet_key: str = "",
) -> list[str]:
    """
    Orchestrates full structural validations using physical expectation counts.

    Args:
        image: Standard BGR input image.
        structure: Loaded model specification JSON dict.
        sheet_key: Normalized sheet key for threshold lookup.

    Returns:
        List of failure codes. Empty list implies perfect validation.
    """
    expected = extract_expected_topology(structure)
    detected = detect_components(image)

    failures: list[str] = []

    content_ratio = compute_content_ratio(image)
    if content_ratio < 0.15:
        failures.append("LAYOUT_COLLAPSE")

    for k in expected:
        if k in ("posts", "beams", "rafters"):
            if "plan" in sheet_key and k == "posts":
                continue
            if k in detected:
                if expected[k] > 0 and detected[k] < expected[k] // 2:
                    failures.append(f"COUNT_MISMATCH_{k.upper()}")

    hub_result = detect_spaghetti_hub(detect_hub_density(image), sheet_key)
    if hub_result:
        failures.append(f"{hub_result['code']}: {hub_result['detail']}")

    brace_result = detect_brace_float(structure)
    if brace_result:
        failures.append(f"{brace_result['code']}: {brace_result['detail']}")

    beam_result = detect_beam_gap(structure)
    if beam_result:
        failures.append(f"{beam_result['code']}: {beam_result['detail']}")

    return failures

# External Comment: Evaluates image using computer vision and returns a report
def evaluate_image_cv(
    img_path: str,
    structure: dict[str, typing.Any],
    sheet_key: str = "",
) -> tuple[dict[str, typing.Any], list[str]]:
    """
    Main cv-evaluation script wrapper that reads path and runs topology heuristics.

    Args:
        img_path: Path to PNG screenshot.
        structure: Loaded structure parameters.
        sheet_key: Normalized sheet key for named-detector threshold lookup.

    Returns:
        Tuple of (cv_metrics, failures).
    """
    metrics: dict[str, typing.Any] = {}
    failures: list[str] = []
    try:
        image = cv2.imread(img_path)
        if image is None:
            return {}, ["IMAGE_LOAD_FAILED"]

        expected = extract_expected_topology(structure)
        detected = detect_components(image)
        content_ratio = compute_content_ratio(image)
        hub_density = detect_hub_density(image)

        metrics["expected_topology"] = expected
        metrics["detected_components"] = detected
        metrics["cv_content_ratio"] = float(content_ratio)
        metrics["cv_hub_density"] = int(hub_density)

        failures = full_visual_validation(image, structure, sheet_key=sheet_key)
    except Exception as e:
        failures.append(f"CV_VALIDATION_ERROR: {str(e)}")
    return metrics, failures

# External Comment: Calculate Discrete Cosine Transform (DCT) based perceptual hash
def compute_phash(img_path: str) -> typing.Optional[int]:
    """
    Computes a 64-bit DCT-based perceptual hash of an image for structural comparison.
    
    Args:
        img_path: Path to the image file.
        
    Returns:
        64-bit integer hash, or None on error.
    """
    try:
        img = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
        if img is None:
            return None
        resized = cv2.resize(img, (32, 32), interpolation=cv2.INTER_AREA)
        dct = cv2.dct(np.float32(resized))
        dct_8x8 = dct[0:8, 0:8]
        avg = np.mean(dct_8x8)
        hash_bits = (dct_8x8 > avg).flatten()
        h = 0
        for bit in hash_bits:
            h = (h << 1) | int(bit)
        return h
    except Exception as e:
        print(f"Failed to compute pHash: {e}")
        return None

# External Comment: Calculate bitwise Hamming distance between hashes
def hamming_distance(h1: int, h2: int) -> int:
    """
    Computes Hamming distance between two 64-bit integer perceptual hashes.
    
    Args:
        h1: First perceptual hash.
        h2: Second perceptual hash.
        
    Returns:
        Integer Hamming distance representing structural differences.
    """
    return bin(h1 ^ h2).count('1')

# External Comment: Compute normalized Mean Absolute Difference (MAD) between two images
def compute_mad(img_path1: str, img_path2: str) -> tuple[float, typing.Optional[str]]:
    """
    Calculates Mean Absolute Difference (MAD) between two images normalized to [0, 1].
    
    Args:
        img_path1: Path to the first image.
        img_path2: Path to the second image.
        
    Returns:
        Tuple of (mad_score, error_message).
    """
    try:
        img1 = cv2.imread(img_path1)
        img2 = cv2.imread(img_path2)
        if img1 is None or img2 is None:
            return 1.0, "IMAGE_LOAD_FAILED"
        if img1.shape != img2.shape:
            img2 = cv2.resize(img2, (img1.shape[1], img1.shape[0]), interpolation=cv2.INTER_AREA)
        diff = np.abs(img1.astype(np.float32) - img2.astype(np.float32))
        mad = np.mean(diff) / 255.0
        return float(mad), None
    except Exception as e:
        return 1.0, f"MAD_COMPUTATION_ERROR: {e}"

