def _sheet_markdown(fr: dict[str, typing.Any]) -> list[str]:
    """Markdown block for one sheet's result."""
    m = fr["metrics"]
    md = [f"### {fr['sheet']}", f"**Status:** **{fr.get('status', 'FAIL')}**  ", f"**SVG:** `{fr['svg']}`  ", f"**PNG:** `{fr['png']}`  "]
    if "hub_crop_png" in fr:
        md += [f"**Hub Crop PNG:** `{fr['hub_crop_png']}`  ", f"**Hub Clip (px):** `{fr['clip'].get('hub_box_px')}`  "]
    md += ["", "#### Metrics",
           f"- non_bg_ratio: `{m.get('non_bg_ratio') or 0.0:.4f}`",
           f"- bbox_fill_ratio: `{m.get('bbox_fill_ratio') or 0.0:.4f}`",
           f"- top_left_clustered: `{bool(m.get('top_left_clustered'))}`"]
    if "cv_content_ratio" in m: md.append(f"- cv_content_ratio: `{m['cv_content_ratio']:.4f}`")
    for key in ("cv_hub_density", "expected_topology", "detected_components"):
        if key in m: md.append(f"- {key}: `{m[key]}`")
    if "hub_edge_density" in m: md.append(f"- hub_edge_density: `{m['hub_edge_density']:.4f}`")
    md += ["", "#### Failures"] + ([f"- {f}" for f in fr["failures"]] or ["- *(none)*"])
    md += ["", "#### Warnings"] + ([f"- {w}" for w in fr["warnings"]] or ["- *(none)*"])
    md += ["", "---"]
    return md


def main() -> None:
    """
    Command line interface entry point orchestrating screenshots and visual assertions.
    """
    args = _parse_args()
    Path(args.out_dir).mkdir(parents=True, exist_ok=True)
    Path(args.report_json).parent.mkdir(parents=True, exist_ok=True)
    Path(args.report_md).parent.mkdir(parents=True, exist_ok=True)

    with open(args.structure) as f:
        structure = json.load(f)
    if not bool(structure.get("geometry", {}).get("_sealed")):
        print("GEOMETRY_NOT_SEALED: Cannot run visual tests on unsealed geometry.")
        sys.exit(1)
    if not (structure.get("meta") or {}).get("source_hash"):
        print("MISSING_INPUT: meta.source_hash — the smoke report must be bound to the structure it checked.")
        sys.exit(1)

    report = _new_report(args, structure)
    overall_failures: list[str] = []
    width = structure["geometry"]["svg_coordinates"]["width_px"]
    height = structure["geometry"]["svg_coordinates"]["height_px"]

    try:
        for sheet in SVG_SHEET_FILENAMES:
            if not (Path(args.svg_dir) / sheet).exists():
                overall_failures.append(f"SVG_MISSING: {sheet}")
                continue
            file_report, failures = _analyze_sheet(sheet, args, structure, width, height)
            report["files"].append(file_report)
            overall_failures.extend(failures)
    except Exception as outer_err:
        print(f"[SMOKE] Visual smoke test critical error: {outer_err}", file=sys.stderr)
        sys.exit(1)

    if overall_failures or any(f.get("status") == "FAIL" for f in report["files"]):
        report["status"] = "FAIL"
        report["may_claim_success"] = False
        report["summary"] = "Visual smoke test failed heuristics."
    report["overall_failures"] = overall_failures

    with open(args.report_json, "w") as f:
        json.dump(report, f, indent=2)
    with open(args.report_md, "w") as f:
        f.write(_render_markdown(report, args))

    if not report["may_claim_success"]:
        sys.exit(1)

if __name__ == "__main__":
    main()
