"""Characterization + C4/C5 binding tests for the Stage 5 drawing red-team gate (run_review)."""
from __future__ import annotations

import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent))
sys.path.insert(0, str(Path(__file__).parent.parent / "scripts"))
from test_cadcraft_e2e_pipeline import SVG_SHEETS, hex_package  # type: ignore[import]  # noqa: E402,F401
import run_drawing_red_team as red_team  # type: ignore[import]  # noqa: E402


def _write_reports(staging: Path, source_hash: str, smoke_ok: bool = True) -> None:
    for name in ("schema-validation-report.json", "physics-validation-report.json"):
        (staging / name).write_text(json.dumps({"source_hash": source_hash, "status": "PASS"}))
    (staging / "visual-smoke-report.json").write_text(json.dumps({
        "source_hash": source_hash, "may_claim_success": smoke_ok,
        "generated_at": datetime.now(timezone.utc).isoformat(), "overall_failures": [], "overall_warnings": [],
    }))


@pytest.fixture
def env(hex_package, tmp_path):
    """A private copy of the real hexagon package's staging + outputs (SVGs generated by render_drawings)."""
    staging, outputs = tmp_path / "staging", tmp_path / "outputs"
    shutil.copytree(hex_package["staging"], staging)
    shutil.copytree(hex_package["outputs"], outputs)
    structure = json.loads((staging / "structure.json").read_text())
    _write_reports(staging, structure["meta"]["source_hash"])
    return {"staging": staging, "outputs": outputs, "structure": structure}


def _review(env, svg_dir=None):
    return red_team.run_review(
        str(svg_dir or env["outputs"]), str(env["staging"] / "structure.json"), str(env["staging"]), str(env["outputs"])
    )


def test_blocked_when_staging_reports_missing(env):
    (env["staging"] / "physics-validation-report.json").unlink()
    report = _review(env)
    assert report["status"] == "BLOCKED" and report["may_claim_success"] is False
    assert report["failure_classification"] == ["MISSING_STAGING_ARTIFACT"]


def test_blocked_on_stale_source_hash(env):
    _write_reports(env["staging"], "stale-hash")
    report = _review(env)
    assert report["status"] == "BLOCKED" and report["failure_classification"] == ["SOURCE_HASH_MISMATCH"]


def test_blocked_without_svgs(env, tmp_path):
    empty = tmp_path / "empty"
    empty.mkdir()
    report = _review(env, svg_dir=empty)
    assert report["status"] == "BLOCKED" and "No SVG files" in report["summary"]


def test_blocked_when_a_required_sheet_is_missing(env):
    (env["outputs"] / SVG_SHEETS[0]).unlink()
    report = _review(env)
    assert report["status"] == "BLOCKED" and report["may_claim_success"] is False
    assert any(SVG_SHEETS[0] in fix for fix in report["overall_required_fixes"])


def test_failed_visual_smoke_denies_approval(env):
    _write_reports(env["staging"], env["structure"]["meta"]["source_hash"], smoke_ok=False)
    report = _review(env)
    assert report["may_claim_success"] is False and report["status"] == "FAIL"


def test_real_pipeline_drawings_are_approved(env):
    report = _review(env)
    assert report["status"] == "PASS", report.get("overall_required_fixes") or [
        (f["file"], f["failure_codes"]) for f in report["files"] if f["status"] != "PASS"
    ]
    assert report["may_claim_success"] is True
    assert len(report["files"]) == len(SVG_SHEETS)
    assert (env["staging"] / "drawing-red-team-report.json").exists()
    assert (env["outputs"] / "drawing-red-team-report.md").exists()


# --- C4/C5: approval is bound to a revision and covers every artifact -------------------------


def test_report_is_bound_to_the_reviewed_revision(env):
    meta = env["structure"]["meta"]
    report = _review(env)
    assert report["revision_id"] == meta["revision_id"]
    assert report["revision_hash"] == meta["revision_hash"]
    assert report["hash_algorithm"] == "gsd-json-v1"
    on_disk = json.loads((env["staging"] / "drawing-red-team-report.json").read_text())
    assert on_disk["revision_id"] == meta["revision_id"]


def test_blocked_reports_are_revision_bound_too(env):
    (env["staging"] / "physics-validation-report.json").unlink()
    report = _review(env)
    assert report["revision_id"] == env["structure"]["meta"]["revision_id"]


def test_missing_dxf_denies_approval(env):
    (env["outputs"] / "cad" / "SB01-structure.dxf").unlink()
    report = _review(env)
    assert report["may_claim_success"] is False
    assert any("MISSING_DXF" in fix for fix in report["overall_required_fixes"])


def test_tampered_dxf_denies_approval(env):
    import ezdxf

    path = env["outputs"] / "cad" / "SB01-structure.dxf"
    doc = ezdxf.readfile(path)
    entity = next(e for e in doc.modelspace() if e.has_xdata("GSD"))
    entity.vertices[0].dxf.location = entity.vertices[0].dxf.location + (5.0, 0, 0)
    doc.saveas(path)
    report = _review(env)
    assert report["may_claim_success"] is False
    assert any("bounds differ" in fix for fix in report["overall_required_fixes"])


def test_missing_or_foreign_cut_list_denies_approval(env):
    cut_list = env["outputs"] / "fabrication" / "cut-list.json"
    data = json.loads(cut_list.read_text())
    data["revision_id"] = "another-revision"
    cut_list.write_text(json.dumps(data))
    assert any("REVISION_MISMATCH" in fix for fix in _review(env)["overall_required_fixes"])
    cut_list.unlink()
    assert any("cut-list.json" in fix for fix in _review(env)["overall_required_fixes"])


def test_unstamped_structure_cannot_be_approved(env):
    structure = env["structure"]
    del structure["meta"]["revision_id"]
    (env["staging"] / "structure.json").write_text(json.dumps(structure))
    report = _review(env)
    assert report["may_claim_success"] is False
    assert report["failure_classification"] == ["MISSING_REVISION_IDENTITY"]
